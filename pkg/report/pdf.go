// PDFOptions configures PDF report generation.
type PDFOptions struct {
	OutputPath      string
	GoVersion       string
	CIReport        *scanner.CIReport
	IntegrityReport *scanner.IntegrityReport

	// Grade is the published grade (Grading v2). nil prints "No grade: grading was not run" instead of a grade.
	Grade *grade.Result

	// StdlibVulns are the standard library vulnerabilities, already sorted by
	// the caller. They are listed in the order given.
	StdlibVulns []scanner.Vulnerability
}

// WritePDF generates an enterprise-grade PDF risk report using UniPDF.
func WritePDF(ctx context.Context, graph *resolver.Graph, ps *scorer.ProjectScore, opts PDFOptions) error {
	rep := progress.From(ctx)

	// Set UniPDF license (metered/API key from env, or unlicensed for open source).
	if err := initLicense(); err != nil {
		fmt.Fprintf(os.Stderr, "warning: UniDoc license error (%v) — PDF output will include a watermark\n", err)
	}

	c := creator.New()
	c.SetPageSize(creator.PageSizeLetter)
	c.SetPageMargins(50, 50, 50, 50)

	// Register fonts.
	helvetica, _ := model.NewStandard14Font(model.HelveticaName)
	helveticaBold, _ := model.NewStandard14Font(model.HelveticaBoldName)

	// Footer on every page.
	c.DrawFooter(func(block *creator.Block, args creator.FooterFunctionArgs) {
		p := c.NewStyledParagraph()
		chunk := p.Append(fmt.Sprintf("Generated by unisupply v%s — unidoc.io/unisupply  |  Page %d of %d", version.String(), args.PageNum, args.TotalPages))
		chunk.Style.Font = helvetica
		chunk.Style.FontSize = 8
		chunk.Style.Color = creator.ColorRGBFromHex("#888888")
		p.SetTextAlignment(creator.TextAlignmentCenter)
		_ = block.Draw(p)
	})

	rep.Step("cover page")
	writeCoverPage(c, graph, opts.Grade, helvetica, helveticaBold)

	rep.Step("executive summary")
	writeExecutiveSummary(c, graph, ps, opts, helvetica, helveticaBold)

	rep.Step("grade section")
	writeGradeSection(c, opts.Grade, helvetica, helveticaBold)

	rep.Step("dependency findings")
	writeDependencyFindings(c, ps, opts.Grade, helvetica, helveticaBold)

	if opts.CIReport != nil {
		rep.Step("CI/CD section")
		writeCISection(c, opts.CIReport, helvetica, helveticaBold)
	}

	if opts.IntegrityReport != nil {
		rep.Step("module directives section")
		writeIntegritySection(c, opts.IntegrityReport, helvetica, helveticaBold)
	}

	if len(opts.StdlibVulns) > 0 {
		rep.Step("standard library vulnerabilities section")
		writeStdlibVulnSection(c, opts.StdlibVulns, helvetica, helveticaBold)
	}

	rep.Step("vulnerability ID appendix")
	writeVulnAliasAppendix(c, ps, opts.StdlibVulns, helvetica, helveticaBold)

	rep.Step("methodology page")
	writeMethodologyPage(c, helvetica, helveticaBold)

	outputPath := opts.OutputPath
	if outputPath == "" {
		outputPath = "unisupply-report.pdf"
	}

	rep.Step("writing %s", outputPath)
	return c.WriteToFile(outputPath)
}

func initLicense() error {
	// Try metered API key from environment.
	// If not set, UniPDF will run in demo mode with watermark.
	if os.Getenv("UNIDOC_LICENSE_API_KEY") != "" {
		return license.SetMeteredKey(os.Getenv("UNIDOC_LICENSE_API_KEY"))
	}
	// Make unlicensed key to avoid errors, but will have watermark.
	lk := license.MakeUnlicensedKey()

	return license.SetLicenseKey("", lk.CustomerName)
}


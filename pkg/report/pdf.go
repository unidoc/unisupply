// gradeFindingByID is the row's finding for an advisory ID, or nil when the row or the finding is not there.
func gradeFindingByID(r *grade.RowResult, id string) *grade.FindingResult {
	if r == nil {
		return nil
	}
	for i := range r.Findings {
		if r.Findings[i].ID == id {
			return &r.Findings[i]
		}
	}
	return nil
}

// vulnTierText names a tier in Grading v2 words.
func vulnTierText(tier string) string {
	switch tier {
	case grade.TierCalled:
		return "called"
	case grade.TierImported:
		return "imported"
	case grade.TierGraphOnly:
		return "graph only: shown, not graded"
	}
	return tier
}

// vulnLine is the first line of a vulnerability: its ID and, from the grade's finding when there is one, the tier, the
// VEX status and the severity as scored. Without a finding (grading did not cover it, e.g. the standard library) it says
// what the scanner reported, in the same words, and does not claim it was graded.
func vulnLine(v *scanner.Vulnerability, f *grade.FindingResult) string {
	if f != nil {
		tier := vulnTierText(f.Tier)
		if f.TierAssumed {
			tier += " (assumed)"
		}
		return fmt.Sprintf("Vulnerability: %s (%s; VEX %s; severity %s)", v.ID, tier, gradeVEXText(f.VEX), gradeFindingSeverity(f))
	}
	var tier string
	switch v.Reachability {
	case "called":
		tier = "called"
	case "imported":
		tier = "imported"
	case "required":
		tier = "graph only: shown, not graded"
	default:
		tier = "reachability not determined"
	}
	sev := v.Severity
	if sev == "" || strings.EqualFold(sev, "UNKNOWN") {
		sev = "not published"
	}
	return fmt.Sprintf("Vulnerability: %s (%s; severity %s)", v.ID, tier, sev)
}

// addVulnBullets appends the bullet lines describing one vulnerability: its
// ID, tier, VEX status, severity as scored and threat-intel badges, the fix,
// the call path and the vulnerable symbols called. f is the grade's finding
// for it (nil when there is none). withSummary adds the advisory summary after
// the first line; dependency blocks omit it.
func addVulnBullets(p *creator.StyledParagraph, v *scanner.Vulnerability, f *grade.FindingResult, withSummary bool, font *model.PdfFont) {
	ti := ""
	if v.InKEV {
		ti = " [KEV — exploited in the wild]"
	}
	addBullet(p, vulnLine(v, f)+ti, font)
	if withSummary && v.Summary != "" {
		addBullet(p, "  Summary: "+v.Summary, font)
	}
	if v.FixedVersion != "" {
		addBullet(p, fmt.Sprintf("  Fix available: %s", v.FixedVersion), font)
	}
	// The ASCII separator is deliberate: see callPathSepPDF.
	if via := reachedVia(v, callPathSepPDF); via != "" {
		addBullet(p, "  Reached via: "+via, font)
	}
	if syms := calledSymbolsLine(v); syms != "" {
		addBullet(p, "  Vulnerable symbols called: "+syms, font)
	}
}

// writeStdlibVulnSection lists the vulnerabilities in the Go standard library
// of the project's toolchain, in the order given. They are not part of any
// dependency's risk score, so they get their own section rather than a
// dependency block.
func writeStdlibVulnSection(c *creator.Creator, vulns []scanner.Vulnerability, regular, bold *model.PdfFont) {
	c.NewPage()
	heading(c, "Standard Library Vulnerabilities", bold)

	intro := c.NewStyledParagraph()
	intro.SetMargins(0, 0, 5, 10)
	ch := intro.Append("These affect the Go standard library used to build dependencies.")
	ch.Style.Font = regular
	ch.Style.FontSize = 10
	_ = c.Draw(intro)

	// One paragraph per vulnerability: the list can run to dozens of entries,
	// which should not be a single paragraph spanning pages.
	for i := range vulns {
		details := c.NewStyledParagraph()
		details.SetMargins(20, 0, 0, 6)
		details.SetLineHeight(1.5)
		addVulnBullets(details, &vulns[i], nil, true, regular)
		_ = c.Draw(details)
	}
}

func writeDependencyBlock(c *creator.Creator, ds *scorer.DependencyScore, row *grade.RowResult, letter string, regular, bold *model.PdfFont, detailed bool) {
	color := pdfLetterColor(letter)

	// Build the classification label for the module header.
	classLabel := "transitive"
	if ds.Direct {
		classLabel = "direct"
	}
	// Append [test-only] when the classification is confirmed (IsTestOnly == &true).
	// When IsTestOnly is nil (unknown) we omit the label — silence is safer than
	// a wrong label.
	if ds.IsTestOnly != nil && *ds.IsTestOnly {
		classLabel += ", test-only"
	}
	// Same rule for [outside build]: only when InBuild is confirmed false.
	if ds.InBuild != nil && !*ds.InBuild {
		classLabel += ", outside build"
	}

	// Module header.
	header := c.NewStyledParagraph()
	header.SetMargins(0, 0, 5, 3)
	ch := header.Append(fmt.Sprintf("%s %s — Grade: %s (%s)", ds.Module, ds.Version, letter, classLabel))
	ch.Style.Font = bold
	ch.Style.FontSize = 11
	ch.Style.Color = color
	_ = c.Draw(header)

	if !detailed {
		return
	}

	details := c.NewStyledParagraph()
	details.SetMargins(20, 0, 0, 10)
	details.SetLineHeight(1.5)

	// Vulnerabilities, known-exploited (KEV) first.
	vulns := make([]scanner.Vulnerability, len(ds.Vulns))
	copy(vulns, ds.Vulns)
	sort.SliceStable(vulns, func(i, j int) bool {
		if vulns[i].InKEV != vulns[j].InKEV {
			return vulns[i].InKEV
		}
		return false
	})
	for i := range vulns {
		addVulnBullets(details, &vulns[i], gradeFindingByID(row, vulns[i].ID), false, regular)
	}

	// Maintenance.
	if ds.Maintenance != nil {
		if ds.Maintenance.MonthsSinceRelease > 0 {
			addBullet(details, fmt.Sprintf("Last release: %d months ago", ds.Maintenance.MonthsSinceRelease), regular)
		}
		if ds.Maintenance.HasActivity() {
			addBullet(details, fmt.Sprintf("Last commit%s: %d months ago", branchSuffix(ds.Maintenance.ActivityBranch), ds.Maintenance.MonthsSinceActivity), regular)
		}
		if ds.Maintenance.Archived {
			addBullet(details, "Repository archived", regular)
		}
		if ds.Maintenance.Deprecated {
			addBullet(details, "Module deprecated"+deprecationSuffix(ds.Maintenance.DeprecationNotice()), regular)
		}
	}

	// Dependency path.
	if len(ds.DependencyPath) > 0 {
		addBullet(details, fmt.Sprintf("Used by: %s", strings.Join(ds.DependencyPath, " → ")), regular)
	}

	_ = c.Draw(details)
}

func pdfRiskColor(level scorer.RiskLevel) creator.Color {
	switch level {
	case scorer.RiskCritical:
		return creator.ColorRGBFromHex("#cc0000")
	case scorer.RiskHigh:
		return creator.ColorRGBFromHex("#e67300")
	case scorer.RiskMedium:
		return creator.ColorRGBFromHex("#ccaa00")
	case scorer.RiskUnknown:
		// Grey, not the default green — an unscored headline must not read as a
		// pass in a report that gets forwarded to people who never ran the scan.
		return creator.ColorRGBFromHex("#666666")
	default:
		return creator.ColorRGBFromHex("#009900")
	}
}
